package dev.spotlight.core

import java.nio.file.Files

fun main() {
    val stone = Entry("minecraft:stone", "Stone", itemId = "minecraft:stone")
    val glowstone = Entry("minecraft:glowstone", "Glowstone", itemId = "minecraft:glowstone")
    val diamond = Entry("minecraft:diamond_sword", "Diamond Sword", itemId = "minecraft:diamond_sword")
    val modded = Entry("example:ruby", "Ruby", "Rare gem", "example:ruby")
    val entries = listOf(glowstone, stone, diamond, modded)
    check(Fuzzy.search("stone", entries).first() == stone)
    check(Fuzzy.search("MINECRAFT:STONE", entries).first() == stone)
    check(Fuzzy.search("example:", entries) == listOf(modded))
    check(Fuzzy.search("dia swo", entries) == listOf(diamond))
    check(Fuzzy.search("dmnd", entries) == listOf(diamond))
    check(Fuzzy.search("stnoe", entries).first() == stone)
    check(Fuzzy.search("diamnd", entries) == listOf(diamond))
    check(Fuzzy.search("rare gem", entries) == listOf(modded))
    check(Fuzzy.search("stone ruby", entries).isEmpty())
    check(Fuzzy.search("zzzzzzzzzz", entries).isEmpty())
    check(Fuzzy.search("", entries) == entries)
    check(Fuzzy.search("", entries, setOf(stone.id), listOf(diamond.id)).take(2) == listOf(stone, diamond))
    check(Fuzzy.search("stone", entries, setOf(glowstone.id)).first() == stone)
    check(Fuzzy.search("", entries, limit = 2) == entries.take(2))
    check(Fuzzy.search("", entries, limit = 0).isEmpty())
    check(Fuzzy.search("", entries, limit = -1).isEmpty())
    check(Fuzzy.search("", List(70) { Entry("$it", "$it") }).size == 60)
    check(Fuzzy.search("  STONE  ", entries) == Fuzzy.search("stone", entries))

    val model = PaletteModel()
    check(model.stage == Stage.ROOT && model.selectedItem == null && model.action == null)
    model.back()
    model.openItems()
    check(model.stage == Stage.ITEMS)
    check(runCatching { model.pickItem(Entry("air", "Air", itemId = "minecraft:air")) }.isFailure)
    check(runCatching { model.pickItem(Entry("action", "Action")) }.isFailure)
    model.pickItem(stone)
    check(model.stage == Stage.ITEM_ACTIONS && model.selectedItem == stone)
    model.startItemAction(ItemAction.PREPARE_GIVE)
    check(model.stage == Stage.QUANTITY && model.action == ItemAction.PREPARE_GIVE)
    check(runCatching { model.startItemAction(ItemAction.COPY_ID) }.isFailure)
    model.back()
    check(model.stage == Stage.ITEM_ACTIONS && model.action == null && model.selectedItem == stone)
    model.startItemAction(ItemAction.COPY_ID)
    check(model.stage == Stage.ITEM_ACTIONS && model.action == ItemAction.COPY_ID)
    model.back()
    check(model.stage == Stage.ITEMS && model.selectedItem == null && model.action == null)
    model.back()
    check(model.stage == Stage.ROOT)
    for (action in ItemAction.entries) {
        model.startItemAction(action)
        check(model.stage == Stage.ITEMS && model.action == action)
        model.pickItem(diamond)
        check(model.selectedItem == diamond && model.action == action)
        check(model.stage == if (action in listOf(ItemAction.PREPARE_GIVE, ItemAction.CREATIVE_GIVE))
            Stage.QUANTITY else Stage.ITEM_ACTIONS)
        model.back()
        check(model.stage == Stage.ITEMS && model.selectedItem == null && model.action == action)
        model.back()
        check(model.stage == Stage.ROOT && model.action == null)
    }
    model.pickItem(stone)
    check(model.stage == Stage.ITEM_ACTIONS)
    for (value in listOf(1, 64, 2304)) check(parseQuantity(value.toString()) == value)
    for (text in listOf("", "0", "-1", "+1", "2305", "1.5", " 1", "1 ", "١", "99999999999999999999")) {
        check(parseQuantity(text) == null) { "Accepted invalid quantity: $text" }
    }

    val directory = Files.createTempDirectory("spotlight-check-")
    try {
        val path = directory.resolve("nested/preferences.properties")
        val preferences = Preferences(path, maxFavorites = 2, maxRecent = 2)
        check(preferences.favorites.isEmpty() && preferences.recent.isEmpty())
        check(preferences.toggleFavorite("minecraft:stone"))
        check(!preferences.toggleFavorite("minecraft:stone"))
        for (id in listOf("one", "two", "three")) preferences.toggleFavorite(id)
        check(preferences.favorites == setOf("two", "three"))
        for (id in listOf("one", "two", "one", "three")) preferences.recordRecent(id)
        check(preferences.recent == listOf("three", "one"))
        preferences.toggleFavorite("mod:宝石=\\\n")
        val loaded = Preferences(path, maxFavorites = 2, maxRecent = 2)
        check(loaded.favorites == preferences.favorites && loaded.recent == preferences.recent)
        check(Preferences(path, maxFavorites = 1, maxRecent = 1).recent == listOf("three"))
        check(runCatching { preferences.recordRecent(" ") }.isFailure)
        val blockedPath = directory.resolve("blocked")
        val blocked = Preferences(blockedPath)
        Files.createDirectory(blockedPath)
        Files.writeString(blockedPath.resolve("keep"), "occupied")
        check(runCatching { blocked.recordRecent("one") }.isFailure)
        check(blocked.recent.isEmpty())
        check(runCatching { blocked.toggleFavorite("one") }.isFailure)
        check(blocked.favorites.isEmpty())
        Files.writeString(path, "recent.count=oops\n")
        check(runCatching { Preferences(path) }.isFailure)
        Files.list(directory).use { paths -> check(paths.noneMatch { it.fileName.toString().endsWith(".tmp") }) }
    } finally {
        Files.walk(directory).use { paths -> paths.sorted(Comparator.reverseOrder()).forEach { Files.delete(it) } }
    }
    println("Core checks passed")
}
